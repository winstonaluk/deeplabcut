# -- the ground-truth end-to-end test --

def _build_synthetic_constant_velocity_descent():
    """Rat sits at the pole top, descends at a perfectly constant velocity,
    then sits at the base -- the ground-truth scenario B4 explicitly asks
    for: 'a fabricated constant-velocity descent must recover the correct
    velocity.'
    """
    fps = 30.0
    pole_length_mm = 1000.0
    base_xy = (100.0, 500.0)
    top_xy = (100.0, 100.0)

    idle_before_frac = np.full(10, 1.0)
    ramp_frac = np.linspace(1.0, 0.0, 61)  # exactly -500mm/s at 30fps (see velocity test above)
    idle_after_frac = np.full(10, 0.0)
    frac = np.concatenate([idle_before_frac, ramp_frac, idle_after_frac])

    y = base_xy[1] - (base_xy[1] - top_xy[1]) * frac  # invert height_fraction's affine map
    x = np.full_like(y, 100.0)  # directly on the pole axis: zero perpendicular offset
    likelihood = np.full_like(y, 1.0)

    n = len(y)
    pole_top_x = np.full(n, top_xy[0])
    pole_top_y = np.full(n, top_xy[1])
    pole_base_x = np.full(n, base_xy[0])
    pole_base_y = np.full(n, base_xy[1])

    return x, y, likelihood, pole_top_x, pole_top_y, pole_base_x, pole_base_y, fps, pole_length_mm


def test_constant_velocity_descent_recovers_correct_velocity():
    x, y, likelihood, pt_x, pt_y, pb_x, pb_y, fps, pole_length_mm = _build_synthetic_constant_velocity_descent()

    result = compute_trial_kinematics(
        x, y, likelihood, pt_x, pt_y, pb_x, pb_y,
        calibration=IDENTITY_CALIBRATION, config=DEFAULT_CONFIG,
        pole_length_mm=pole_length_mm, fps=fps,
    )

    assert result.descent_onset_frame is not None
    assert result.descent_offset_frame is not None
    assert result.mean_velocity_mm_s == pytest.approx(500.0, rel=0.05)
    # onset/offset trim inward from the full ramp at the 0.95/0.05 crossings
    # (frac[3]=0.95, frac[57]=0.05 within the 61-point ramp): (57-3)/30 = 1.8s,
    # not the full ramp's ~1.97s.
    assert result.descent_duration_s == pytest.approx(1.8, rel=0.05)
    assert result.pole_landmark_drift_flagged is False
    assert result.occlusion_fraction == pytest.approx(0.0)
    assert result.height_mm[0] == pytest.approx(1000.0, abs=1.0)
    assert result.height_mm[-1] == pytest.approx(0.0, abs=1.0)
    np.testing.assert_allclose(result.perpendicular_mm, 0.0, atol=1e-6)


def test_constant_velocity_descent_with_a_short_occlusion_gap_still_recovers_velocity():
    """The same scenario, but with a short mid-descent occlusion (likelihood
    drop) that's well within max_gap_frames -- gap interpolation should
    bridge it cleanly enough that velocity recovery is unaffected."""
    x, y, likelihood, pt_x, pt_y, pb_x, pb_y, fps, pole_length_mm = _build_synthetic_constant_velocity_descent()
    likelihood = likelihood.copy()
    likelihood[40:43] = 0.1  # 3-frame occlusion, within max_gap_frames=5

    result = compute_trial_kinematics(
        x, y, likelihood, pt_x, pt_y, pb_x, pb_y,
        calibration=IDENTITY_CALIBRATION, config=DEFAULT_CONFIG,
        pole_length_mm=pole_length_mm, fps=fps,
    )

    assert result.mean_velocity_mm_s == pytest.approx(500.0, rel=0.05)
    assert result.is_interpolated[40:43].all()


def test_constant_velocity_descent_with_a_long_occlusion_gap_stays_nan_in_output():
    """A gap longer than max_gap_frames must stay NaN all the way through
    to the final height_mm output -- never silently bridged."""
    x, y, likelihood, pt_x, pt_y, pb_x, pb_y, fps, pole_length_mm = _build_synthetic_constant_velocity_descent()
    likelihood = likelihood.copy()
    likelihood[40:50] = 0.1  # 10-frame occlusion, beyond max_gap_frames=5

    result = compute_trial_kinematics(
        x, y, likelihood, pt_x, pt_y, pb_x, pb_y,
        calibration=IDENTITY_CALIBRATION, config=DEFAULT_CONFIG,
        pole_length_mm=pole_length_mm, fps=fps,
    )

    assert np.all(np.isnan(result.height_mm[40:50]))
    assert not result.is_interpolated[40:50].any()


def test_trial_summary_and_kinematics_long_rows_are_consistent():
    x, y, likelihood, pt_x, pt_y, pb_x, pb_y, fps, pole_length_mm = _build_synthetic_constant_velocity_descent()
    result = compute_trial_kinematics(
        x, y, likelihood, pt_x, pt_y, pb_x, pb_y,
        calibration=IDENTITY_CALIBRATION, config=DEFAULT_CONFIG,
        pole_length_mm=pole_length_mm, fps=fps,
    )

    summary = to_trial_summary_row("uid-1", "mid_back", result)
    long_rows = to_kinematics_long_rows("uid-1", "lateral_L", "mid_back", result)

    assert summary.trial_uid == "uid-1"
    assert summary.mean_velocity_mm_s == pytest.approx(result.mean_velocity_mm_s)
    assert len(long_rows) == len(result.height_mm)
    assert long_rows[0].trial_uid == "uid-1"
    assert long_rows[0].view == "lateral_L"
