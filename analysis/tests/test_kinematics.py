def test_compute_velocity_of_a_linear_ramp_is_constant():
    fps = 30.0
    height_mm = np.linspace(1000.0, 0.0, 61)  # -1000mm over 60 frames = -500mm/s at 30fps
    velocity = compute_velocity(height_mm, fps)
    np.testing.assert_allclose(velocity[2:-2], -500.0, atol=1e-6)


