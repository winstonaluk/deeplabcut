# -- step 1: likelihood filter --

def test_apply_likelihood_filter_masks_below_cutoff():
    x = np.array([1.0, 2.0, 3.0])
    y = np.array([10.0, 20.0, 30.0])
    likelihood = np.array([0.9, 0.3, 0.9])
    x_f, y_f = apply_likelihood_filter(x, y, likelihood, cutoff=0.5)
    assert np.isnan(x_f[1]) and np.isnan(y_f[1])
    assert x_f[0] == 1.0 and x_f[2] == 3.0


# -- step 2: gap interpolation --

def test_interpolate_gaps_short_gap_is_filled():
    arr = np.array([1.0, np.nan, np.nan, 4.0])  # gap of 2
    result = interpolate_gaps(arr, max_gap_frames=2)
    np.testing.assert_allclose(result, [1.0, 2.0, 3.0, 4.0])


def test_interpolate_gaps_long_gap_stays_nan():
    """A gap longer than max_gap_frames must stay NaN -- never silently
    bridged (overnight-prompt.md explicit requirement)."""
    arr = np.array([1.0, np.nan, np.nan, np.nan, np.nan, 6.0])  # gap of 4
    result = interpolate_gaps(arr, max_gap_frames=2)
    assert np.all(np.isnan(result[1:5]))
    assert result[0] == 1.0 and result[5] == 6.0


def test_interpolate_gaps_edge_gap_stays_nan():
    arr = np.array([np.nan, np.nan, 3.0, 4.0])  # leading edge gap
    result = interpolate_gaps(arr, max_gap_frames=5)
    assert np.all(np.isnan(result[:2]))


# -- step 3: smoothing --

def test_smooth_median_preserves_unfilled_nan_positions():
    arr = np.array([1.0, 2.0, np.nan, np.nan, np.nan, np.nan, 7.0])  # gap of 4, too long for max_gap=2
    interpolated = interpolate_gaps(arr, max_gap_frames=2)
    smoothed = smooth(interpolated, "median", window=3)
    assert np.all(np.isnan(smoothed[2:6]))


def test_smooth_unknown_method_raises():
    with pytest.raises(ValueError):
        smooth(np.array([1.0, 2.0, 3.0]), "not_a_real_method", window=3)


def test_smooth_median_is_near_identity_on_a_linear_ramp():
    arr = np.linspace(0.0, 100.0, 50)
    smoothed = smooth(arr, "median", window=3)
    np.testing.assert_allclose(smoothed[1:-1], arr[1:-1], atol=1e-9)


# -- step 4: undistortion --

def test_undistort_points_identity_calibration_is_passthrough():
    x = np.array([10.0, 20.0, np.nan])
    y = np.array([30.0, 40.0, np.nan])
    x_u, y_u = undistort_points(x, y, IDENTITY_CALIBRATION)
    np.testing.assert_allclose(x_u[:2], x[:2], atol=1e-6)
    np.testing.assert_allclose(y_u[:2], y[:2], atol=1e-6)
    assert np.isnan(x_u[2]) and np.isnan(y_u[2])


def test_undistort_points_recovers_true_pixels_with_real_distortion():
    """Ground truth generated by cv2.projectPoints itself: distort known
    object points into pixel space, then confirm undistort_points recovers
    the same pixels a zero-distortion projection would have produced."""
    camera_matrix = np.array([[800.0, 0.0, 320.0], [0.0, 800.0, 240.0], [0.0, 0.0, 1.0]])
    dist_coeffs = np.array([0.1, -0.05, 0.001, 0.001, 0.0])
    calibration = CalibrationRecord(
        camera_serial="s", epoch_id="e",
        camera_matrix=tuple(tuple(row) for row in camera_matrix),
        distortion_coefficients=tuple(dist_coeffs),
    )

    object_points = np.array([[0.05, 0.03, 1.0], [-0.02, 0.04, 1.0], [0.0, 0.0, 1.0]])
    rvec = np.zeros(3)
    tvec = np.zeros(3)
    distorted, _ = cv2.projectPoints(object_points, rvec, tvec, camera_matrix, dist_coeffs)
    distorted = distorted.reshape(-1, 2)
    true_pixels, _ = cv2.projectPoints(object_points, rvec, tvec, camera_matrix, np.zeros(5))
    true_pixels = true_pixels.reshape(-1, 2)

    x_u, y_u = undistort_points(distorted[:, 0], distorted[:, 1], calibration)

    np.testing.assert_allclose(x_u, true_pixels[:, 0], atol=0.5)
    np.testing.assert_allclose(y_u, true_pixels[:, 1], atol=0.5)


